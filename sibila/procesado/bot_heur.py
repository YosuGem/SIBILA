"""Heurísticas de bot (spec §6.5; umbrales FIJADOS de Fase 0).

Función pura: ninguna flag usa reloj; solo published_at/historial_autor del
contexto. Las 4 claves SIEMPRE presentes (auditable). Subir la lista de
marcadores o los umbrales = subir BOT_VERSION (= re-ejercicio, D-B4-04).
"""
from dataclasses import dataclass
from datetime import datetime

BOT_VERSION = "bot-1"

# Umbrales congelados (provisionales Fase 1, plan Lovelace §4.6)
_UMBRAL_CV = 0.1          # regularidad: CV = σ/μ de intervalos < 0,1
_UMBRAL_PLANTILLA = 0.8   # 1 − |únicos|/|totales| de trigramas ≥ 0,8
_MIN_TRIGRAMAS = 10
_UMBRAL_RAFAGA = 20       # ≥20 publicaciones en alguna ventana de 3 600 s
_VENTANA_S = 3600
_MIN_HISTORIAL = 5

# Marcadores congelados ES/EN (DATO del módulo; subirla = subir BOT_VERSION).
MARCADORES = (
    "como modelo de lenguaje",
    "soy una ia",
    "soy un modelo de lenguaje",
    "como inteligencia artificial",
    "como ia no puedo",
    "lo siento, no puedo",
    "lo siento, pero no puedo",
    "no puedo cumplir",
    "no puedo ayudarte con eso",
    "generado por inteligencia artificial",
    "as an ai language model",
    "i am an ai language model",
    "i'm an ai language model",
    "as a language model",
    "i cannot fulfill",
    "i cannot comply",
    "i cannot assist with",
    "i'm sorry, but i can't",
    "i am sorry, but i cannot",
    "generated by",
)


@dataclass(frozen=True)
class ContextoBot:
    published_at: "str | None"      # ISO del doc
    fetched_at: str
    author_hash: "str | None"
    texto_limpio: str
    historial_autor: tuple          # published_at ISO del MISMO autor, ASC


def _segundos(iso: str) -> float:
    return datetime.fromisoformat(iso).timestamp()


def _flag_regularidad(ctx: ContextoBot) -> bool:
    if ctx.author_hash is None or len(ctx.historial_autor) < _MIN_HISTORIAL:
        return False  # no evaluable ≠ sospechoso
    ts = sorted(_segundos(t) for t in ctx.historial_autor)
    intervalos = [b - a for a, b in zip(ts, ts[1:])]
    if len(intervalos) < 2:
        return False
    mu = sum(intervalos) / len(intervalos)
    if mu <= 0:
        return False
    var = sum((x - mu) ** 2 for x in intervalos) / len(intervalos)
    return (var ** 0.5) / mu < _UMBRAL_CV


def _flag_plantilla(ctx: ContextoBot) -> bool:
    w = ctx.texto_limpio.split()
    tri = [" ".join(w[k:k + 3]) for k in range(len(w) - 2)]
    if len(tri) < _MIN_TRIGRAMAS:
        return False
    return 1 - len(set(tri)) / len(tri) >= _UMBRAL_PLANTILLA


def _flag_marcador(ctx: ContextoBot) -> bool:
    return any(m in ctx.texto_limpio for m in MARCADORES)


def _flag_rafaga(ctx: ContextoBot) -> bool:
    if ctx.author_hash is None:
        return False
    inst = [_segundos(t) for t in ctx.historial_autor]
    if ctx.published_at is not None:
        inst.append(_segundos(ctx.published_at))
    inst.sort()
    # Máximo de publicaciones en cualquier ventana deslizante de 3 600 s.
    j = 0
    mejor = 0
    for i in range(len(inst)):
        while inst[i] - inst[j] >= _VENTANA_S:
            j += 1
        mejor = max(mejor, i - j + 1)
    return mejor >= _UMBRAL_RAFAGA


def flags(ctx: ContextoBot) -> dict:
    """Las 4 claves de spec §6.5, siempre presentes."""
    return {
        "regularidad": _flag_regularidad(ctx),
        "plantilla": _flag_plantilla(ctx),
        "marcador": _flag_marcador(ctx),
        "rafaga": _flag_rafaga(ctx),
    }
